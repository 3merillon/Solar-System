// Licence notices of the Rust crates compiled into the browser WASM (solar-explorer for
// wasm32, normal dependencies only), from each crate's own licence files in the cargo
// registry. Writes web/THIRD-PARTY-RUST.txt, which the packager ships next to the WASM.
// Run after a change to Cargo.lock: node tools/Rust-Notices.mjs
import {execFileSync} from 'node:child_process';
import {readdirSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
const cargo = (...a) => execFileSync('cargo', ['+1.87.0', ...a], {encoding: 'utf8', maxBuffer: 1 << 28});
const shipped = new Set(cargo('tree', '-p', 'solar-explorer', '--target', 'wasm32-unknown-unknown', '-e', 'normal', '--prefix', 'none', '--locked')
  .split('\n').map(l => l.replace(/ \(.*$/, '').trim()).filter(Boolean).map(l => l.replace(/ v/, ' ')));
const meta = JSON.parse(cargo('metadata', '--format-version', '1', '--locked'));
const crates = meta.packages.filter(p => p.source && shipped.has(`${p.name} ${p.version}`)).sort((a, b) => a.name.localeCompare(b.name));
const out = [
  'Rust crates compiled into the Solar-System v2 WebAssembly module (pkg/solar_explorer_bg.wasm).',
  'Generated by tools/Rust-Notices.mjs from Cargo.lock; each entry reproduces the licence files the crate publishes.',
  `${crates.length} crates.`, '',
];
const missing = [], seen = new Map();
for (const p of crates) {
  const dir = dirname(p.manifest_path);
  const files = readdirSync(dir).filter(f => /^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE)/i.test(f)).sort();
  out.push('='.repeat(78), `${p.name} ${p.version} (${p.license || p.license_file || 'no licence field'})`, p.repository || '', '='.repeat(78));
  if (!files.length) { missing.push(p.name); out.push(`(The crate publishes no licence file; its manifest declares: ${p.license}.)`, ''); continue; }
  for (const f of files) {
    const text = readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trimEnd(), key = text.replace(/\s+/g, ' ');
    // A licence text already reproduced word for word is referenced, not repeated.
    if (seen.has(key)) out.push(`--- ${f}: identical to ${seen.get(key)} above`, '');
    else { seen.set(key, `${p.name} ${f}`); out.push(`--- ${f}`, text, ''); }
  }
}
writeFileSync('web/THIRD-PARTY-RUST.txt', out.join('\n') + '\n');
console.log(JSON.stringify({crates: crates.length, without_licence_file: missing}));
