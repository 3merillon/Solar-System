// M1 gate: GPU mesh heights match the independent f64 page reader within the existing tolerance,
// 0.02 m + 2e-6 x |height| (docs/SINGLE-SKIN.md).
import {tileServer,earthBrowser,settle,toEye,heading} from './Earth-Test-Lib.mjs';
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
const arg=(k,d)=>{const i=process.argv.indexOf('--'+k);return i<0?d:process.argv[i+1];};
const dir=resolve(arg('output','evidence/local/real-earth/runs/height-audit'));await mkdir(dir,{recursive:true});
const tour=JSON.parse(await readFile('tools/fixtures/earth-tour.json','utf8'));
// Each route in a browser of its own. A stale row needs its node generated before the page it reads arrives, so the route decides how many show: a row on the cube edge stayed 509 m off coming from orbit, where only the pinned pack is up,
// and 19 m coming from Dents, while this gate read Lausanne, Dents, edge-cross alone. Unequal shared samples count too: the same point on the body, cached at two heights, means one of them is stale.
const ROUTES=arg('stops')?[arg('stops').split(',')]:[['lausanne','dents-du-midi','edge-cross'],['edge-cross'],['corner']];
const server=await tileServer();
const report={tolerance:'0.02 m + 2e-6 x |height|',stops:[]};
try{
 for(const [route,names] of ROUTES.entries()){
 let b;
 try{
 b=await earthBrowser(resolve(dir,`route-${route}`),server,{view:'earth-orbit',width:640,height:360});
 await b.evaluate(`solarExplorer.engine.profiling(true);solarExplorer.configure({clouds:false,water:false,trees:false,rocks:false})`);
 for(const name of names){
  const s=tour.stops.find(t=>t.name===name),eye=toEye(s.lon,s.lat,s.alt),f=heading(s.lon,s.lat,s.heading);
  await b.evaluate(`solarExplorer.camera=${JSON.stringify([eye,eye.map((v,i)=>v+f[i]*1000)])};`);
  const settled=await settle(b,{maxFrames:20000});
  // One more settled stretch, so that nodes regenerated by the last pages have published.
  await b.evaluate(`(async()=>{for(let i=0;i<120;i++){while(!solarExplorer.step(1/60))await new Promise(r=>setTimeout(r,0));await new Promise(r=>setTimeout(r,2));}})()`);
  const audit=JSON.parse(await b.evaluate('solarExplorer.engine.audit_geometry()'));
  const row={samples_over_tolerance:audit.samples_over_tolerance,largest_excess_over_tolerance_m:audit.largest_excess_over_tolerance_m,worst:audit.worst_height_sample,over:audit.over_tolerance_samples,served_level_disagreements:audit.served_level_disagreements,height_error_where_served_differs_m:audit.height_error_where_served_differs_m,height_error_where_served_agrees_m:audit.height_error_where_served_agrees_m,stop:name,quiet:settled.quiet,lag:settled.lag,filtered_height_samples:audit.filtered_height_samples,max_height_error_m:audit.max_height_error_m,max_position_error_m:audit.max_position_error_m,boundary_edges:audit.boundary_edges,nonmanifold_edges:audit.nonmanifold_edges,topology_overflow:audit.topology_overflow,nonfinite:audit.nonfinite_samples,unequal_shared:audit.unequal_shared_samples,max_height_m:9000};
  row.route=names.join(',');
  row.pass=audit.samples_over_tolerance===0&&audit.unequal_shared_samples===0&&audit.boundary_edges===0&&audit.nonmanifold_edges===0&&audit.topology_overflow===0;
  report.stops.push(row);console.log(JSON.stringify(row));
 }
 }finally{if(b)await b.close();}
 }
 report.pass=report.stops.every(s=>s.pass);
 console.log(JSON.stringify({pass:report.pass,stops:report.stops.length}));
 await writeFile(resolve(dir,'report.json'),JSON.stringify(report,null,1));
}finally{server.close();}
